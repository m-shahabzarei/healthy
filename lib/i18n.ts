export function translate(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const template = locale === 'fa' ? translations[key] ?? key : key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function translateError(locale: Locale, message: string): string {
  if (locale === 'en') return message;
  return translations[message] ?? 'عملیات انجام نشد. دوباره تلاش کنید.';
}

export function formatNumber(locale: Locale, value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(locale === 'fa' ? 'fa-IR' : 'en-US', options).format(value);
}

export function formatDate(locale: Locale, value: string | Date, options: Intl.DateTimeFormatOptions): string {
  const date = typeof value === 'string' ? new Date(value.includes('T') ? value : `${value.slice(0, 10)}T12:00:00`) : value;
  if (Number.isNaN(date.getTime())) return typeof value === 'string' ? value : '';
  return new Intl.DateTimeFormat(locale === 'fa' ? 'fa-IR' : 'en-US', options).format(date);
}

export function normalizeLocalizedNumber(value: string): string {
  return value.replace(/[۰-۹]/g, (digit) => String(digit.charCodeAt(0) - 1776))
    .replace(/[٠-٩]/g, (digit) => String(digit.charCodeAt(0) - 1632))
    .replace(/[٫،,]/g, '.').trim();
}
